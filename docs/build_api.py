def pixi_tasks() -> dict[str, list[str]]:
    """{script path: [pixi tasks that run it]}."""
    config = tomllib.loads((REPO / "pixi.toml").read_text(encoding="utf-8"))
    tasks = dict(config.get("tasks", {}))
    for feature in config.get("feature", {}).values():
        tasks.update(feature.get("tasks", {}))
    found: dict[str, list[str]] = {}
    for name, task in tasks.items():
        cmd = task if isinstance(task, str) else task.get("cmd", "")
        for path in re.findall(r"[\w/]+\.py", cmd if isinstance(cmd, str) else " ".join(cmd)):
            found.setdefault(path, []).append(name)
    return found


def script_list() -> dict[str, list[str]]:
    groups = {k: list(v) for k, v in SCRIPT_GROUPS.items()}
    listed = {p for v in groups.values() for p in v}
    for pattern in SCRIPT_GLOBS:
        for path in sorted(REPO.glob(pattern)):
            rel = path.relative_to(REPO).as_posix()
            if rel not in listed:
                groups.setdefault("Other scripts", []).append(rel)
    return groups


