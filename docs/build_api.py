# Docstring (plain text + a little reST) -> MyST markdown
# ═════════════════════════════════════════════════════════════════════════════

ROLE = re.compile(r":(?:func|class|mod|meth|attr|data|obj|exc):`([^`]+)`")
DOUBLE_CODE = re.compile(r"``(.+?)``")
SINGLE_CODE = re.compile(r"(?<!`)`([^`\n]+)`(?!`)")
MATH = re.compile(r"\$\$.+?\$\$|\$[^$\n]+\$")
DOTTED = re.compile(r"(?<![\w/.`])(fluxpy(?:\.\w+)+)")
LIST_ITEM = re.compile(r"^(\s*)([*-]|\d+\.)\s+")
PANEL_ITEM = re.compile(r"^\(([a-z](?:\s*[-–]\s*[a-z])?(?:,\s*[a-z])*)\)\s+")
CODE_ENTRY = re.compile(r"^((?:``[^`]+``(?:\s*,\s*)?)+)\s{2,}(\S.*)$")
COLON_ENTRY = re.compile(r"^(\*{0,2}[A-Za-z_]\w*(?:\s*,\s*\*{0,2}[A-Za-z_]\w*)*)\s*:\s+(.*)$")
TABLE_BORDER = re.compile(r"^\s*=+(\s+=+)+\s*$")
UNDERLINE = re.compile(r"^\s*([=\-~^])\1{2,}\s*$")


class Converter:
    def __init__(self, index: Index, module: str | None, base: str = ""):
        self.index = index
        self.module = module
        self.base = base                    # prefix of API page links written from outside docs/api/

    # ── inline ────────────────────────────────────────────────────────────────
    def inline(self, text: str) -> str:
        """reST roles and literals -> MyST links and code; dotted fluxpy names -> links."""
        out, pos = [], 0
        pattern = re.compile("|".join(f"(?:{p.pattern})" for p in (MATH, ROLE, DOUBLE_CODE, SINGLE_CODE)))
        for m in pattern.finditer(text):
            out.append(self._plain(text[pos:m.start()]))
            token = m.group(0)
            if token.startswith("$"):
                out.append(token)
            elif token.startswith(":"):
                target = ROLE.match(token).group(1)
                out.append(self.index.link(target, self.module, base=self.base) or code(target.lstrip("~")))
            else:
                content = token.strip("`") if token.startswith("``") else token[1:-1]
                out.append(self.index.link(content, self.module, base=self.base) or code(content))
            pos = m.end()
        out.append(self._plain(text[pos:]))
        return "".join(out)

    def _plain(self, text: str) -> str:
        def repl(m):
            name = m.group(1)
            return self.index.link(name, None, base=self.base) or name
        return DOTTED.sub(repl, text)

    def plain_code(self, text: str) -> str:
        """Inside a code block: roles and literals reduced to their text."""
        text = ROLE.sub(lambda m: m.group(1).lstrip("~"), text)
        return DOUBLE_CODE.sub(lambda m: m.group(1), text)

    # ── blocks ────────────────────────────────────────────────────────────────
    def blocks(self, text: str, colon_entries: bool = False) -> str:
        lines = text.splitlines()
        out: list[str] = []
        i, n = 0, len(lines)
        list_indent: int | None = None
        in_panel = False                     # the current list item is a figure panel "(a) ..."
        literal_next = False

        def indent_of(s: str) -> int:
            return len(s) - len(s.lstrip(" "))

        def blank_line():
            if out and out[-1] != "":
                out.append("")

        while i < n:
            line = lines[i]
            stripped = line.strip()
            indent = indent_of(line)
            if not stripped:
                out.append("")
                i += 1
                continue

            # simple reST table
            if TABLE_BORDER.match(line):
                in_list = list_indent is not None and indent >= list_indent
                i = self._table(lines, i, out, " " * list_indent if in_list else "")
                if not in_list:
                    list_indent = None
                continue

            # underlined heading -> bold paragraph (keeps the page's table of contents clean)
            if indent == 0 and i + 1 < n and UNDERLINE.match(lines[i + 1]) \
                    and len(lines[i + 1].strip()) >= len(stripped) - 3:
                blank_line()
                out += [f"**{self.inline(stripped)}**", ""]
                i += 2
                list_indent = None
                continue

            # doctest
            if stripped.startswith(">>>"):
                j = i
                while j < n and lines[j].strip():
                    j += 1
                blank_line()
                out += ["```python", *[s.strip() for s in lines[i:j]], "```", ""]
                i = j
                continue

            # indented material
            if indent >= 2 and not (list_indent is not None and indent >= list_indent):
                j, block = self._take_indented(lines, i, indent)
                blank_line()
                if block[0].lstrip().startswith("$$"):
                    out += [b.strip() for b in block] + [""]
                else:
                    language = "python" if literal_next else "text"
                    out += [f"```{language}", *[self.plain_code(b) for b in block], "```", ""]
                literal_next = False
                list_indent = None
                i = j
                continue
            if list_indent is not None and indent >= list_indent + 4 and out and out[-1] == "":
                j, block = self._take_indented(lines, i, indent)
                pad = " " * list_indent
                if block[0].lstrip().startswith("$$"):
                    out += [pad + b.strip() for b in block] + [""]
                else:
                    out += [pad + "```text", *[pad + self.plain_code(b) for b in block], pad + "```", ""]
                i = j
                continue

            # definition entries: ``name``  description   /   name : description
            m = CODE_ENTRY.match(line) if indent == 0 else None
            if m is None and colon_entries and indent == 0:
                m = COLON_ENTRY.match(line)
            if m:
                names = re.findall(r"``([^`]+)``", m.group(1)) or [s.strip() for s in m.group(1).split(",")]
                desc = m.group(2).strip()
                i += 1
                while i < n and lines[i].strip() and indent_of(lines[i]) >= 2:
                    desc += " " + lines[i].strip()
                    i += 1
                shown = ", ".join(self.index.link(x, self.module, base=self.base) or code(x) for x in names)
                if out and out[-1] != "" and not out[-1].startswith("* "):
                    out.append("")
                out.append(f"* {shown}: {self.inline(desc)}")
                list_indent = 2
                continue

            # figure panels "(a) ...", "(a-d) ..." -> list items with the panel letters in bold
            m = PANEL_ITEM.match(line) if indent == 0 else None
            if m:
                if out and out[-1] != "" and list_indent is None:
                    out.append("")
                list_indent = len(m.group(0))
                in_panel = True
                out.append(f"* **({m.group(1)})** " + self.inline(line[m.end():]))
                i += 1
                continue

            # list items and their continuation lines
            m = LIST_ITEM.match(line)
            if m:
                if out and out[-1] != "" and list_indent is None:
                    out.append("")
                list_indent = len(m.group(0))
                in_panel = False
                out.append(self.inline(line))
                i += 1
                continue
            if list_indent is not None and indent >= list_indent:
                out.append("  " + self.inline(stripped) if in_panel else self.inline(line))
                i += 1
                continue

            # ordinary paragraph line
            if list_indent is not None:
                blank_line()
                list_indent = None
            if stripped.endswith("::"):
                literal_next = True
                stripped = stripped[:-2].rstrip()
                if stripped:
                    out.append(self.inline(stripped) + ":")
                i += 1
                continue
            out.append(self.inline(stripped))
            i += 1

        text = "\n".join(out)
        text = re.sub(r"\n{3,}", "\n\n", text)
        return text.strip("\n")

    @staticmethod
    def _take_indented(lines: list[str], i: int, min_indent: int) -> tuple[int, list[str]]:
        """Lines from ``i`` on that are indented by at least ``min_indent`` (blank lines inside
        the block included), dedented."""
        j = i
        block: list[str] = []
        while j < len(lines):
            s = lines[j]
            if s.strip() and len(s) - len(s.lstrip(" ")) >= min_indent:
                block.append(s)
                j += 1
            elif not s.strip():
                k = j
                while k < len(lines) and not lines[k].strip():
                    k += 1
                if k < len(lines) and len(lines[k]) - len(lines[k].lstrip(" ")) >= min_indent:
                    block += [""] * (k - j)
                    j = k
                else:
                    break
            else:
                break
        cut = min(len(s) - len(s.lstrip(" ")) for s in block if s.strip())
        return j, [s[cut:] for s in block]

    def _table(self, lines: list[str], i: int, out: list[str], pad: str = "") -> int:
        """A reST simple table (borders of '=') -> a markdown table (indented by ``pad`` inside a
        list item); returns the next line index."""
        border = lines[i]
        spans = [(m.start(), m.end()) for m in re.finditer(r"=+", border)]
        rows, j, borders = [], i + 1, 1
        while j < len(lines) and borders < 3:
            if TABLE_BORDER.match(lines[j]):
                borders += 1
                j += 1
                continue
            if not lines[j].strip():
                break
            cells = []
            for k, (a, b) in enumerate(spans):
                end = spans[k + 1][0] if k + 1 < len(spans) else None
                cells.append(lines[j][a:end].strip())
            rows.append(cells)
            j += 1
        if out and out[-1] != "":
            out.append("")
        header, body = rows[0], rows[1:]
        cell = lambda s: self.inline(s).replace("|", "\\|")        # noqa: E731
        out.append(pad + "| " + " | ".join(cell(c) for c in header) + " |")
        out.append(pad + "|" + "|".join("---" for _ in header) + "|")
        out += [pad + "| " + " | ".join(cell(c) for c in r) + " |" for r in body]
        out.append("")
        return j


def strip_title(doc: str) -> tuple[str, str]:
    """Remove the reST title block ('fluxpy.x' underlined with '=') of a module docstring.

    Returns (tagline, rest): the text after a dash in the title, if any, and the body."""
    lines = doc.splitlines()
    if len(lines) > 1 and UNDERLINE.match(lines[1]):
        title = lines[0]
        tagline = re.split(r"\s+[—–-]{1,2}\s+", title, maxsplit=1)
        return (tagline[1].strip() if len(tagline) > 1 else ""), "\n".join(lines[2:]).strip("\n")
    return "", doc


def split_sections(doc: str) -> tuple[str, dict[str, str], str]:
    """(body before the sections, {numpydoc section: text}, body after them)."""
    lines = doc.splitlines()
    before: list[str] = []
    after: list[str] = []
    sections: dict[str, list[str]] = {}
    current: str | None = None
    i = 0
    while i < len(lines):
        line = lines[i]
        title = line.strip()
        if title in NUMPYDOC_SECTIONS and i + 1 < len(lines) and UNDERLINE.match(lines[i + 1]):
            current = title
            sections[current] = []
            i += 2
            continue
        if current is None:
            (after if sections else before).append(line)
        elif current == "Parameters" and title and line == line.lstrip() and not COLON_ENTRY.match(line) \
                and sections[current] and not sections[current][-1].strip():
            current = None                                  # prose after the parameter list
            after.append(line)
        else:
            sections[current].append(line)
        i += 1
    return "\n".join(before).strip("\n"), {k: "\n".join(v).strip("\n") for k, v in sections.items()}, \
        "\n".join(after).strip("\n")


def parameter_docs(text: str) -> dict[str, str]:
    """{name: description} from a numpydoc 'Parameters' section ('a, b : text' entries)."""
    docs: dict[str, str] = {}
    current: list[str] = []
    for line in text.splitlines():
        m = COLON_ENTRY.match(line) if line == line.lstrip() else None
        if m:
            current = [s.strip().lstrip("*") for s in m.group(1).split(",")]
            for name in current:
                docs[name] = m.group(2).strip()
        elif line.strip() and current:
            for name in current:
                docs[name] += " " + line.strip()
    return docs


def summary_of(doc: str) -> str:
    """The first sentence of the first paragraph of a docstring."""
    paragraph = []
    for line in doc.strip().splitlines():
        if not line.strip():
            break
        paragraph.append(line.strip())
    text = " ".join(paragraph)
    for m in re.finditer(r"\.(\s|$)", text):
        before = re.findall(r"([\w.]+)$", text[:m.start()])
        if before and (before[0] in ABBREVIATIONS or before[0].split(".")[-1] in ABBREVIATIONS):
            continue
        if m.start() < 20:
            continue
        return text[:m.start() + 1]
    return text.rstrip(",:;")


