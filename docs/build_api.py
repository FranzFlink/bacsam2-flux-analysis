def braced(text: str, start: int) -> tuple[str, int]:
    """Content of the {...} group that opens at ``text[start]``, and the index after it."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{" and text[i - 1] != "\\":
            depth += 1
        elif text[i] == "}" and text[i - 1] != "\\":
            depth -= 1
            if depth == 0:
                return text[start + 1:i], i + 1
    raise ValueError("unbalanced braces")


def latex_to_md(tex: str) -> str:
    """A figure caption of the reading copy (LaTeX, references already resolved) as MyST markdown;
    math stays as $...$."""
    out = []
    for k, part in enumerate(re.split(r"(\$[^$]+\$)", tex)):
        if k % 2:                                             # math
            out.append(part)
            continue
        for command, mark in (("textbf", "**"), ("emph", "*"), ("textit", "*")):
            part = re.sub(r"\\" + command + r"\{([^{}]*)\}", lambda m: f"{mark}{m.group(1)}{mark}", part)
        part = (part.replace("---", "—").replace("--", "–").replace("~", " ").replace("\\,", " ")
                .replace("\\%", "%").replace("\\&", "&").replace("\\textmu ", "µ").replace("\\textdegree", "°"))
        out.append(part)
    text = " ".join("".join(out).split())
    leftover = re.findall(r"\\[A-Za-z]+", re.sub(r"\$[^$]+\$", "", text))
    if leftover:
        print(f"  warning: LaTeX commands left in a caption: {sorted(set(leftover))}")
    return text


def manuscript_captions() -> dict[str, str]:
    """{figure script name: caption as markdown}, from the reading copy of the manuscript."""
    if not MANUSCRIPT_COPY.exists():
        return {}
    tex = MANUSCRIPT_COPY.read_text(encoding="utf-8")
    captions = {}
    for env in re.findall(r"\\begin\{figure\*?\}(.*?)\\end\{figure\*?\}", tex, flags=re.S):
        graphic = re.search(r"\\includegraphics(?:\[[^]]*\])?\{([^}]+)\}", env)
        start = env.find("\\caption{")
        if graphic and start >= 0:
            caption, _ = braced(env, start + len("\\caption"))
            captions[Path(graphic.group(1)).stem] = latex_to_md(caption)
    return captions


def figure_dependencies(source: str, index: Index) -> list[str]:
    """Links to the fluxpy modules and objects and the scripts that a figure script imports."""
    links = []
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.ImportFrom) and node.module:
            if node.module == "fluxpy":
                targets = [f"fluxpy.{a.name}" for a in node.names]
            elif node.module.startswith("fluxpy."):
                targets = [f"{node.module}.{a.name}" for a in node.names]
            elif (REPO / "scripts" / f"{node.module}.py").exists():
                targets = [f"scripts/{node.module}.py"]
            else:
                continue
            for target in targets:
                link = index.link(target, None, base="../api/")
                if link and link not in links:
                    links.append(link)
    return links


def render_figure(name: str, number: str, title: str, section: str, chapter: str, caption: str,
                  index: Index) -> str:
    rel = f"figures_manuscript/{name}.py"
    source = (REPO / rel).read_text(encoding="utf-8")
    doc = ast.get_docstring(ast.parse(source)) or ""
    lines = doc.splitlines()
    if lines and re.match(r"^(Fig\.|Figure)\s", lines[0]):          # the title line; the page has its own
        lines = lines[1:]
    kept, skip = [], False
    for line in lines:                                              # "Run:" lines: see Reproduction
        if line.startswith("Run:"):
            skip = True
            continue
        if skip and line.startswith(" "):
            continue
        skip = False
        kept.append(line)
    description = Converter(index, None, base="../api/").blocks("\n".join(kept).strip("\n"))
    width = re.search(r"width=fs\.(COL_W|MID_W|FULL_W)|figsize=\(fs\.(COL_W|MID_W|FULL_W)", source)
    width_text = WIDTHS[width.group(1) or width.group(2)] if width else None
    uses = figure_dependencies(source, index)
    chapter_no = int(chapter[:2])

    out = ["---", f"title: \"Figure {number} · {title}\"", f"short_title: \"Fig. {number} · {title}\"",
           "---", "", GENERATED, "",
           f"**Paper:** {section}  ·  **Script:** [{code(rel)}](#{rel})  ·  "
           f"**Method:** [Chapter {chapter_no}](../../book/{chapter}.ipynb)", "",
           f":::{{figure}} ../../figures_manuscript/output/{name}.png",
           f":alt: Figure {number} of the paper",
           (f"**Figure {number}.** {caption}" if caption else f"**Figure {number}.**"),
           ":::", ""]
    if description:
        out += ["## Construction", "", description, ""]
    out += ["## Reproduction", "", "```bash", f"pixi run python {rel}", "```", "",
            f"The script writes `figures_manuscript/output/{name}.pdf` and `.png`"
            + (f" at the printed width ({width_text})" if width_text else " at the printed size")
            + "; `pixi run figures` writes all figures."
            + (" It uses " + ", ".join(uses) + "." if uses else ""), "",
            f":::{{dropdown}} Source code ({rel})", "````python", source.rstrip("\n"), "````", ":::"]
    return finish(out)


def render_figures_index(captions: dict[str, str]) -> str:
    out = ["---", "title: Figures", "short_title: Figures",
           "description: \"The figures of the paper with their captions, construction and the scripts that "
           "produce them.\"", "---", "", GENERATED, "",
           "Each figure of the paper is produced by one script in `figures_manuscript/` at its printed size, "
           "styled by [`fluxpy.figstyle`](../api/fluxpy.figstyle.md) (one font size, one colour per flux estimate). "
           "The pages show each figure with its caption from the paper, its construction, the code it depends "
           "on and the script itself. `pixi run figures` rebuilds all figures (about 3 minutes; Figures 1, 4 "
           "and 5 download map data once).", "",
           "::::{grid} 1 2 2 2", ""]
    for name, number, title, section, _ in FIGURES:
        out += [f":::{{card}} Figure {number} · {title}", f":link: {name}.md",
                f"![Figure {number}](../../figures_manuscript/output/{name}.png)", "",
                f"{section}", ":::", ""]
    out += ["::::"]
    return finish(out)


def figure_pages(index: Index) -> dict[Path, str]:
    scripts = {p.stem for p in (REPO / "figures_manuscript").glob("fig*.py")}
    listed = {f[0] for f in FIGURES}
    if scripts != listed:
        raise SystemExit(f"FIGURES in docs/build_api.py out of date: not listed {sorted(scripts - listed)}, "
                         f"no such script {sorted(listed - scripts)}")
    captions = manuscript_captions()
    pages = {FIG_DIR / "index.md": render_figures_index(captions)}
    for name, number, title, section, chapter in FIGURES:
        pages[FIG_DIR / f"{name}.md"] = render_figure(name, number, title, section, chapter,
                                                      captions.get(name, ""), index)
    return pages


