#!/usr/bin/env python3
"""Write the API reference (``docs/api/``) and the figure pages (``docs/figures/``) of the website.

MyST, the engine of the website, has no autodoc. This script does what Sphinx's
autodoc and autosummary do for a Sphinx site:

* one page per ``fluxpy`` module, in the order of the module map in
  ``fluxpy/__init__.py`` (paper order): the module docstring, a summary table, every
  public constant (value and the ``#:`` comment of its definition), class (fields with
  type, default and meaning) and function (signature, parameter table with types and
  defaults, docstring), each with a link to the source on GitHub and the source itself;
* one page on every script (``scripts/``, ``figures_manuscript/``, the book, paper and
  website builders): its docstring and the pixi task that runs it;
* an index page;
* one page per manuscript figure (``docs/figures/``): the figure, its caption from the
  reading copy of the manuscript (``paper/manuscript_clean.tex``), the docstring of its
  script, the fluxpy objects it uses, and the script itself.

Docstrings are plain text with a little reStructuredText (````code````, ``:func:``
roles, underlined headings, numpydoc ``Parameters`` sections, simple tables, ``::``
literal blocks) and ``$...$`` math; they are translated to MyST markdown here, and
every name that is documented becomes a link.

The pages are committed like the executed book chapters, so the website build needs
neither the data nor the analysis environment. ``tests/test_api_docs.py`` fails when a
docstring or signature changed and the pages were not rebuilt.

Run:  pixi run api
"""
