def build() -> dict[Path, str]:
    """{output path: page text} of every page of the API reference and of the figure pages."""
    modules = [load_module(short, paper) for short, paper in module_map()]
    index = Index()
    for mod in modules:
        index.add_page(mod.name, f"{mod.name}.md")
        for item in mod.items:
            if item.kind == "constant":
                index.add_label(item.qualname, constants_label(mod.name))
            else:
                index.add_label(item.qualname, label_of(item.qualname))
            if item.kind == "class":
                for node in item.node.body:
                    if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
                        q = f"{item.qualname}.{node.name}"
                        index.add_label(q, label_of(q))
    for mod in modules:                                   # re-exported names point at their origin
        for name, origin in mod.reexports:
            if origin in index.targets:
                index.targets[f"{mod.name}.{name}"] = index.targets[origin]
    for paths in script_list().values():
        for rel in paths:
            index.add_label(rel, rel)
    for notebook in sorted((REPO / "book").glob("*.ipynb")):
        index.add_page(f"book/{notebook.name}", f"../../book/{notebook.name}")

    pages = {OUT_DIR / "index.md": render_index(modules, index),
             OUT_DIR / "scripts.md": render_scripts(index)}
    for mod in modules:
        pages[OUT_DIR / f"{mod.name}.md"] = render_module(mod, index)
    pages.update(figure_pages(index))
    return pages


OUTPUT_DIRS = (OUT_DIR, FIG_DIR)


def toc_missing(pages: dict[Path, str]) -> list[str]:
    """Pages that myst.yml does not list in its table of contents."""
    toc = (REPO / "myst.yml").read_text(encoding="utf-8")
    return [p.relative_to(REPO).as_posix() for p in pages if p.relative_to(REPO).as_posix() not in toc]


def main(argv: list[str]) -> int:
    pages = build()
    for folder in OUTPUT_DIRS:
        folder.mkdir(parents=True, exist_ok=True)
    stale = [p for folder in OUTPUT_DIRS for p in folder.glob("*.md") if p not in pages]
    for path in stale:
        path.unlink()
        print(f"removed {path.relative_to(REPO).as_posix()}")
    for path, text in pages.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(REPO).as_posix()}")
    missing = toc_missing(pages)
    if missing:
        print("add to the toc in myst.yml: " + ", ".join(missing))
        return 1
    print(f"API reference and figure pages: {len(pages)} pages in docs/api/ and docs/figures/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
