@dataclass
class Item:
    """One documented object of a module."""
    kind: str                      # "constant", "class", "function"
    name: str
    qualname: str                  # fluxpy.module.name
    node: ast.AST | None
    obj: object
    doc: str = ""                  # docstring, or the #: comment of a constant
    start: int = 0                 # first source line (decorators included)
    end: int = 0


@dataclass
class Module:
    name: str                      # fluxpy.eddy_covariance
    short: str                     # eddy_covariance
    path: Path
    paper: str                     # paper sections from the module map
    source: str
    lines: list[str]
    tree: ast.Module
    comments: dict[int, str]       # line -> comment text (without '#')
    comment_only: set[int]         # lines that hold nothing but a comment
    items: list[Item] = field(default_factory=list)
    reexports: list[tuple[str, str]] = field(default_factory=list)    # (name, qualname of the origin)


def module_map() -> list[tuple[str, str]]:
    """(module, paper sections) in the order of the module map of fluxpy/__init__.py."""
    rows: list[tuple[str, str]] = []
    for line in inspect.getdoc(fluxpy).splitlines():
        m = re.match(r"^(\S.*?)\s\.{3,}\s(\w+(?:,\s*\w+)*)", line)
        if m:
            for name in (s.strip() for s in m.group(2).split(",")):
                rows.append((name, m.group(1).strip()))
    present = {m.name for m in pkgutil.iter_modules(fluxpy.__path__)}
    listed = [name for name, _ in rows]
    missing, unknown = present - set(listed), set(listed) - present
    if missing or unknown:
        raise SystemExit(f"module map in fluxpy/__init__.py out of date: not listed {sorted(missing)}, "
                         f"no such module {sorted(unknown)}")
    return rows


def scan_comments(source: str) -> tuple[dict[int, str], set[int]]:
    """Every comment of a source file by line, and the lines that hold only a comment."""
    comments, comment_only = {}, set()
    code_lines: set[int] = set()
    for tok in tokenize.generate_tokens(io.StringIO(source).readline):
        if tok.type == tokenize.COMMENT:
            comments[tok.start[0]] = tok.string[1:]
        elif tok.type not in (tokenize.NL, tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT,
                              tokenize.ENDMARKER):
            code_lines.update(range(tok.start[0], tok.end[0] + 1))
    comment_only = {line for line in comments if line not in code_lines}
    return comments, comment_only


def doc_comments(nodes: list[ast.stmt], comments: dict[int, str], comment_only: set[int],
                 plain_trailing: bool = False) -> dict[int, str]:
    """The ``#:`` documentation comment of each assignment in ``nodes`` (keyed by id(node)).

    Sphinx convention: ``#:`` lines directly above the assignment, or a ``#:`` comment
    after it on the same line; ``#:`` lines directly below such a trailing comment
    continue it. With ``plain_trailing`` an ordinary trailing ``#`` comment counts too
    (the style of fluxpy.figstyle).
    """
    docs: dict[int, str] = {}
    claimed: set[int] = set()
    for node in nodes:
        parts: list[str] = []
        above = []
        line = node.lineno - 1
        while line in comment_only and comments[line].startswith(":") and line not in claimed:
            above.insert(0, line)
            line -= 1
        parts += [comments[k][1:].strip() for k in above]
        claimed.update(above)
        trailing = comments.get(node.end_lineno) if node.end_lineno not in comment_only else None
        if trailing is not None and (trailing.startswith(":") or plain_trailing):
            parts.append(trailing[1:].strip() if trailing.startswith(":") else trailing.strip())
            line = node.end_lineno + 1
            while line in comment_only and comments[line].startswith(":"):
                parts.append(comments[line][1:].strip())
                claimed.add(line)
                line += 1
        if parts:
            docs[id(node)] = " ".join(" ".join(parts).split())
    return docs


def written(node: ast.AST, source: str) -> str:
    """The expression as written in the source (``2.0e-4``, not ``0.0002``), on one line."""
    text = ast.get_source_segment(source, node) or ast.unparse(node)
    return " ".join(text.split()) if "\n" in text else text


def assigned_name(node: ast.stmt) -> str | None:
    if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
        return node.targets[0].id
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        return node.target.id
    return None


def first_line(node: ast.AST) -> int:
    decorators = getattr(node, "decorator_list", [])
    return min([node.lineno] + [d.lineno for d in decorators])


def load_module(short: str, paper: str) -> Module:
    name = f"fluxpy.{short}"
    obj = importlib.import_module(name)
    path = Path(obj.__file__)
    source = path.read_text(encoding="utf-8")
    comments, comment_only = scan_comments(source)
    mod = Module(name=name, short=short, path=path, paper=paper, source=source,
                 lines=source.splitlines(), tree=ast.parse(source), comments=comments,
                 comment_only=comment_only)
    exported = getattr(obj, "__all__", None)
    constant_docs = doc_comments(mod.tree.body, comments, comment_only, plain_trailing=True)
    defined: set[str] = set()

    for node in mod.tree.body:
        name_ = assigned_name(node)
        if name_ is not None:
            defined.add(name_)
            doc = constant_docs.get(id(node), "")
            if name_.startswith("_") or not (name_.isupper() or doc or (exported and name_ in exported)):
                continue
            if any(i.name == name_ for i in mod.items):          # assigned twice: keep the first
                continue
            mod.items.append(Item("constant", name_, f"{name}.{name_}", node, getattr(obj, name_), doc,
                                  node.lineno, node.end_lineno))
        elif isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            defined.add(node.name)
            if node.name.startswith("_"):
                continue
            kind = "class" if isinstance(node, ast.ClassDef) else "function"
            mod.items.append(Item(kind, node.name, f"{name}.{node.name}", node, getattr(obj, node.name),
                                  ast.get_docstring(node) or "", first_line(node), node.end_lineno))
    for name_ in exported or []:
        if name_ not in defined:
            origin = getattr(obj, name_)
            origin_module = getattr(origin, "__module__", None)
            if origin_module is None or origin_module == name:          # a constant imported from elsewhere
                origin_module = next(m for m in (f"fluxpy.{s}" for s, _ in module_map())
                                     if name_ in vars(importlib.import_module(m))
                                     and m != name and _defines(m, name_))
            mod.reexports.append((name_, f"{origin_module}.{name_}"))
    return mod


def _defines(module: str, name: str) -> bool:
    tree = ast.parse(Path(importlib.import_module(module).__file__).read_text(encoding="utf-8"))
    return any(assigned_name(n) == name or getattr(n, "name", None) == name for n in tree.body)


