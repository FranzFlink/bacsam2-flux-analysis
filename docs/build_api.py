class Index:
    """Everything a docstring can link to: modules, objects, scripts, book chapters."""

    def __init__(self):
        self.targets: dict[str, tuple[str, str]] = {}      # name -> ("page" | "label", target)

    def add_page(self, name: str, page: str):
        self.targets[name] = ("page", page)

    def add_label(self, name: str, label: str):
        self.targets[name] = ("label", label)

    def resolve(self, text: str, module: str | None) -> tuple[str, str] | None:
        t = text.strip().lstrip("~").removesuffix("()")
        if not re.fullmatch(r"[\w./-]+", t):
            return None
        candidates = [t]
        if module:
            candidates.append(f"{module}.{t}")
        candidates.append(f"fluxpy.{t}")
        for c in candidates:
            if c in self.targets:
                return self.targets[c]
        return None

    def link(self, text: str, module: str | None, display: str | None = None, base: str = "") -> str | None:
        """Markdown link to ``text``, or None. ``base`` is prepended to the path of an API page
        when the link is written from outside docs/api/."""
        target = self.resolve(text, module)
        if target is None:
            return None
        shown = code(display if display is not None else text.strip().lstrip("~"))
        kind, where = target
        if kind == "page":
            return f"[{shown}]({where if where.startswith('../') else base + where})"
        return f"[{shown}](#{where})"


def code(text: str) -> str:
    """Inline code that may itself contain backticks."""
    if "`" in text:
        return f"`` {text} ``"
    return f"`{text}`"


def label_of(qualname: str) -> str:
    return qualname


def constants_label(module: str) -> str:
    return f"{module}--constants"


