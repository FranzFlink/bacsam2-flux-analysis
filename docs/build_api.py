def format_default(node: ast.expr | None, value, source: str) -> str:
    """Default as written in the source, with its value when that is an expression."""
    if node is None:
        return "required"
    text = written(node, source)
    shown = code(text)
    if value is not inspect.Parameter.empty and value is not MISSING and simple(value) \
            and not is_literal(node):
        r = short_repr(value)
        if r != text and len(r) <= 30:
            shown += f" (= {code(r)})"
    return shown


def is_literal(node: ast.expr) -> bool:
    try:
        ast.literal_eval(node)
        return True
    except (ValueError, TypeError, SyntaxError, MemoryError, RecursionError):
        return False


def simple(value) -> bool:
    if isinstance(value, (bool, int, float, str, type(None))):
        return True
    if isinstance(value, (tuple, list)) and len(value) <= 12:
        return all(isinstance(v, (bool, int, float, str, type(None))) for v in value)
    return False


def short_repr(value) -> str:
    if isinstance(value, float):
        return repr(value) if len(repr(value)) <= 10 else f"{value:.6g}"
    if isinstance(value, (tuple, list)):
        inner = ", ".join(short_repr(v) for v in value)
        return f"({inner},)" if isinstance(value, tuple) and len(value) == 1 else \
            (f"({inner})" if isinstance(value, tuple) else f"[{inner}]")
    return repr(value)


def signature_lines(name: str, fn: ast.FunctionDef, source: str, method: bool = False) -> list[str]:
    """The signature as written in the source, one parameter per line when long."""
    a = fn.args
    parts: list[str] = []

    def fmt(arg: ast.arg, default: ast.expr | None) -> str:
        s = arg.arg
        if arg.annotation is not None:
            s += ": " + written(arg.annotation, source)
        if default is not None:
            s += (" = " if arg.annotation is not None else "=") + written(default, source)
        return s

    positional = a.posonlyargs + a.args
    defaults = [None] * (len(positional) - len(a.defaults)) + list(a.defaults)
    for k, (arg, default) in enumerate(zip(positional, defaults)):
        if method and k == 0 and arg.arg in ("self", "cls"):
            continue
        parts.append(fmt(arg, default))
        if a.posonlyargs and k == len(a.posonlyargs) - 1:
            parts.append("/")
    if a.vararg:
        parts.append("*" + fmt(a.vararg, None))
    elif a.kwonlyargs:
        parts.append("*")
    for arg, default in zip(a.kwonlyargs, a.kw_defaults):
        parts.append(fmt(arg, default))
    if a.kwarg:
        parts.append("**" + fmt(a.kwarg, None))
    returns = f" -> {written(fn.returns, source)}" if fn.returns is not None else ""
    one_line = f"{name}({', '.join(parts)}){returns}"
    if len(one_line) <= 90:
        return [one_line]
    return [f"{name}(", *[f"    {p}," for p in parts], f"){returns}"]


def parameter_table(fn: ast.FunctionDef, obj, docs: dict[str, str], conv: Converter, source: str,
                    method: bool = False) -> list[str]:
    a = fn.args
    try:
        runtime = inspect.signature(obj).parameters
    except (TypeError, ValueError):
        runtime = {}
    positional = a.posonlyargs + a.args
    defaults = [None] * (len(positional) - len(a.defaults)) + list(a.defaults)
    rows = []
    entries = list(zip(positional, defaults))
    if method and entries and entries[0][0].arg in ("self", "cls"):
        entries = entries[1:]
    entries += list(zip(a.kwonlyargs, a.kw_defaults))
    for arg, default in entries:
        value = runtime[arg.arg].default if arg.arg in runtime else inspect.Parameter.empty
        rows.append((arg.arg, arg.annotation, format_default(default, value, source), arg in a.kwonlyargs))
    if a.vararg:
        rows.append(("*" + a.vararg.arg, a.vararg.annotation, "", False))
    if a.kwarg:
        rows.append(("**" + a.kwarg.arg, a.kwarg.annotation, "", False))
    if not rows:
        return []
    unknown = set(docs) - {r[0].lstrip("*") for r in rows}
    if unknown:
        print(f"  warning: {conv.module}.{fn.name}: documented parameters not in the signature: {sorted(unknown)}")
    with_docs = any(r[0].lstrip("*") in docs for r in rows)
    header = "| Parameter | Type | Default |" + (" Description |" if with_docs else "")
    out = [header, "|---|---|---|" + ("---|" if with_docs else "")]
    for name, annotation, default, keyword_only in rows:
        type_ = code(written(annotation, source)).replace("|", "\\|") if annotation is not None else ""
        shown = code(name) + (" (keyword)" if keyword_only else "")
        row = f"| {shown} | {type_} | {default.replace('|', chr(92) + '|')} |"
        if with_docs:
            row += f" {conv.inline(docs.get(name.lstrip('*'), '')).replace('|', chr(92) + '|')} |"
        out.append(row)
    return out


def render_docstring(doc: str, conv: Converter) -> tuple[str, dict[str, str], str, str]:
    """(body markdown, parameter docs, returns markdown, markdown after the sections)."""
    before, sections, after = split_sections(doc)
    params = parameter_docs(sections.get("Parameters", ""))
    returns = conv.blocks(sections["Returns"], colon_entries=True) if "Returns" in sections else ""
    extra = []
    for name, text in sections.items():
        if name not in ("Parameters", "Returns"):
            extra.append(f"**{name}**\n\n{conv.blocks(text)}")
    body_after = "\n\n".join([*extra, conv.blocks(after)] if after else extra)
    return conv.blocks(before), params, returns, body_after


def render_function(mod: Module, item: Item, conv: Converter, level: int = 3, method: bool = False,
                    shown_name: str | None = None) -> list[str]:
    fn = item.node
    name = shown_name or item.name
    is_property = any(ast.unparse(d) == "property" for d in fn.decorator_list)
    out = [f"({label_of(item.qualname)})=", f"{'#' * level} {code(name)}" + (" (property)" if is_property else ""),
           ""]
    decorators = [f"@{written(d, mod.source)}" for d in fn.decorator_list]
    returns_type = written(fn.returns, mod.source) if fn.returns is not None else None
    if is_property:
        sig = [name.split(".")[-1] + (f": {returns_type}" if returns_type else "")]
    else:
        sig = signature_lines(name.split(".")[-1], fn, mod.source, method)
    out += ["```python", *decorators, *sig, "```", ""]
    body, params, returns, after = render_docstring(item.doc, conv)
    if body:
        out += [body, ""]
    if not is_property:
        table = parameter_table(fn, item.obj, params, conv, mod.source, method)
        if table:
            out += ["**Parameters**", "", *table, ""]
    if returns_type or returns:
        head = "**Returns**" + (f" {code(returns_type)}" if returns_type else "")
        out += [head + (":" if returns else ""), ""]
        if returns:
            out += [returns, ""]
    if after:
        out += [after, ""]
    out += [f"[Source on GitHub]({source_url(mod.path, item.start, item.end)})", ""]
    if not method:                                   # a method's source is in its class's box
        out += source_dropdown(mod, item) + [""]
    return out


def dataclass_fields(mod: Module, item: Item) -> list[tuple[str, str, str, str]]:
    """(name, type, default, meaning) of the fields of a dataclass, from its source."""
    body = [n for n in item.node.body if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name)]
    docs = doc_comments(body, mod.comments, mod.comment_only)
    defaults = {f.name: f.default for f in fields(item.obj)} if is_dataclass(item.obj) else {}
    rows = []
    for node in body:
        value = defaults.get(node.target.id, MISSING)
        rows.append((node.target.id, written(node.annotation, mod.source),
                     format_default(node.value, value, mod.source), docs.get(id(node), "")))
    return rows


def render_class(mod: Module, item: Item, conv: Converter, index: Index) -> list[str]:
    cls = item.node
    decorators = [f"@{written(d, mod.source)}" for d in cls.decorator_list]
    bases = f"({', '.join(written(b, mod.source) for b in cls.bases)})" if cls.bases else ""
    out = [f"({label_of(item.qualname)})=", f"### {code(item.name)}", "",
           "```python", *decorators, f"class {item.name}{bases}", "```", ""]
    doc = item.doc
    if doc:
        body, params, returns, after = render_docstring(doc, conv)
        out += [body, ""]
        if after:
            out += [after, ""]
    rows = dataclass_fields(mod, item)
    if rows:
        out += ["**Fields**", "", "| Field | Type | Default | Meaning |", "|---|---|---|---|"]
        for name, type_, default, meaning in rows:
            out.append(f"| {code(name)} | {code(type_).replace('|', chr(92) + '|')} | "
                       f"{default.replace('|', chr(92) + '|')} | {conv.inline(meaning).replace('|', chr(92) + '|')} |")
        out.append("")
    for node in cls.body:
        if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
            member = Item("function", node.name, f"{item.qualname}.{node.name}", node,
                          getattr(item.obj, node.name), ast.get_docstring(node) or "",
                          first_line(node), node.end_lineno)
            out += render_function(mod, member, conv, level=4, method=True,
                                   shown_name=f"{item.name}.{node.name}")
    out += [f"[Source on GitHub]({source_url(mod.path, item.start, item.end)})", ""]
    out += source_dropdown(mod, item) + [""]
    return out


def constant_value(mod: Module, item: Item) -> tuple[str, bool]:
    """(value cell, whether the full definition is shown below the table)."""
    node = item.node
    text = written(node.value, mod.source) if node.value is not None else ""
    value = item.obj
    if simple(value):
        r = short_repr(value)
        if len(text) <= 80:
            evaluated = not is_literal(node.value) and r != text and len(r) <= 40
            return code(text) + (f" = {code(r)}" if evaluated else ""), False
        return (code(r) if len(r) <= 80 else f"{type(value).__name__}, see below"), len(r) > 80
    if isinstance(value, dict):
        keys = list(value)
        if all(isinstance(k, str) for k in keys) and len(", ".join(keys)) <= 120:
            cell = f"`dict` with the keys {', '.join(code(k) for k in keys)}"
        else:
            cell = f"`dict` with {len(keys)} entries"
        return cell, len(text) > 50
    if len(text) <= 80:
        return code(text), False
    return f"{type(value).__name__}, see below", True


def render_constants(mod: Module, items: list[Item], conv: Converter) -> list[str]:
    out = [f"({constants_label(mod.name)})=", "## Constants", "",
           "| Name | Value | Meaning |", "|---|---|---|"]
    long_ones = []
    for item in items:
        cell, long_ = constant_value(mod, item)
        out.append(f"| {code(item.name)} | {cell.replace('|', chr(92) + '|')} | "
                   f"{conv.inline(item.doc).replace('|', chr(92) + '|')} |")
        if long_:
            long_ones.append(item)
    out.append("")
    for item in long_ones:
        body = "\n".join(mod.lines[item.start - 1:item.end])
        out += [f":::{{dropdown}} {item.name} (definition)", "````python", body, "````", ":::", ""]
    out += [f"[Source on GitHub]({GITHUB_BLOB}/{mod.path.relative_to(REPO).as_posix()})", ""]
    return out


def render_module(mod: Module, index: Index) -> str:
    conv = Converter(index, mod.name)
    tagline, doc = strip_title(inspect.getdoc(importlib.import_module(mod.name)) or "")
    summary = tagline or summary_of(doc)
    rel = mod.path.relative_to(REPO).as_posix()
    out = ["---", f"title: {mod.name}", f"short_title: {mod.short}",
           f"description: {yaml_str(strip_markup(summary))}", "---", "", GENERATED, ""]
    out += [f"**Paper:** {mod.paper}  ·  **Source:** [{rel}]({GITHUB_BLOB}/{rel})", ""]
    if tagline:
        out += [conv.inline(tagline), ""]
    out += [conv.blocks(doc), ""]

    constants = [i for i in mod.items if i.kind == "constant"]
    classes = [i for i in mod.items if i.kind == "class"]
    functions = [i for i in mod.items if i.kind == "function"]

    out += ["## Summary", "", "| Name | Kind | Summary |", "|---|---|---|"]
    for item in constants + classes + functions:
        target = constants_label(mod.name) if item.kind == "constant" else label_of(item.qualname)
        summary_ = item.doc if item.kind == "constant" else summary_of(item.doc)
        out.append(f"| [{code(item.name)}](#{target}) | {item.kind} | "
                   f"{conv.inline(summary_).replace('|', chr(92) + '|')} |")
    for name, origin in mod.reexports:
        out.append(f"| {index.link(origin, None, name)} | re-exported | "
                   f"defined in {index.link(origin.rsplit('.', 1)[0], None)} |")
    out.append("")

    if constants:
        out += render_constants(mod, constants, conv)
    if classes:
        out += ["## Classes", ""]
        for item in classes:
            out += render_class(mod, item, conv, index)
    if functions:
        out += ["## Functions", ""]
        for item in functions:
            out += render_function(mod, item, conv)
    return finish(out)


def strip_markup(text: str) -> str:
    text = ROLE.sub(lambda m: m.group(1).lstrip("~"), text)
    return DOUBLE_CODE.sub(lambda m: m.group(1), text).replace("`", "")


def yaml_str(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def finish(lines: list[str]) -> str:
    """Join the lines of a page; runs of blank lines outside code blocks become one."""
    out: list[str] = []
    fence: str | None = None
    for line in "\n".join(lines).split("\n"):
        m = re.match(r"^\s*(`{3,})", line)
        if m and (fence is None or m.group(1) == fence):
            fence = None if fence else m.group(1)
        if fence is None and not line.strip() and out and not out[-1].strip():
            continue
        out.append(line)
    return "\n".join(out).rstrip("\n") + "\n"


